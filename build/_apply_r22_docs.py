"""一次性把 R22 的结果写进六份文档（跑完即删）。"""
from pathlib import Path

R = Path(".")


def edit(name: str, pairs: list[tuple[str, str]], must: bool = True) -> None:
    p = R / name
    s = p.read_text(encoding="utf-8")
    for old, new in pairs:
        if old not in s:
            if must:
                raise SystemExit(f"[{name}] 找不到锚点：{old[:60]}")
            continue
        s = s.replace(old, new, 1)
    p.write_text(s, encoding="utf-8")
    print(f"✔ {name}")


